#!/usr/bin/env python3
"""Phase 0.2's verdict across seeds (PLAN: "measured as rates over k runs, never one run").

Reads the results of several spike runs made with the same code and writes ../docs/spike-go-no-go.md:
each seed's four gates, how many seeds passed each gate, and the economics per seed. The verdict is
GO only if every seed is GO — a gate that passes on some seeds is a rate, and the rate is reported.

  python3 aggregate.py runs/A runs/B runs/C [--before runs/X]   # --before: a pre-fix run, shown apart
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from economics import econ

HERE = Path(__file__).resolve().parent
GATES = ("G1", "G2", "G3", "G4")


def seed_of(run: Path) -> str:
    """From the report; else from a "-s<seed>" folder name; a run cut off before its report says so."""
    rep = run / "report.md"
    if rep.exists():
        m = re.search(r"seed (\d+)", rep.read_text())
        if m:
            return m.group(1)
    m = re.search(r"-s(\d+)$", run.name)
    return m.group(1) if m else "?"


def row(run: Path, label: str | None = None) -> dict:
    res = json.loads((run / "results.json").read_text())
    res = {t: r for t, r in res.items() if "metrics" in r}   # a run cut off mid-task keeps its finished tasks
    seed = label or seed_of(run)
    if not (run / "report.md").exists():
        seed += " (cut off)"
    return {"run": run, "seed": seed, "tasks": {t: r["metrics"] for t, r in res.items()},
            "go": all(r["metrics"][g] for r in res.values() for g in GATES), "econ": {e["task"]: e for e in econ(run)}}


def table(rows: list[dict]) -> list[str]:
    pct = lambda x: "—" if x is None else f"{100 * x:.0f}%"  # noqa: E731
    out = ["| Seed | Task | G1 steps on habits | G2 held-out accuracy (coverage) | G3 token drop | G4 odd answered wrongly | Break-even day | Steady × cheaper |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        for task, m in r["tasks"].items():
            e = r["econ"][task]
            out.append(f"| {r['seed']} | {task} | {pct(m['steps_on_habits_last5'])} {'✓' if m['G1'] else '✗'} | "
                       f"{pct(m['heldout_accuracy'])} ({pct(m['heldout_coverage'])}) {'✓' if m['G2'] else '✗'} | "
                       f"{m['token_ratio']:.1f}× {'✓' if m['G3'] else '✗'}"
                       f"{(' (robust ' + format(m['token_ratio_robust'], '.1f') + '×)') if 'token_ratio_robust' in m else ''} | "
                       f"{m['odd_wrong']} of {m['odd_answered']} {'✓' if m['G4'] else '✗'} | "
                       f"{e['breakeven'] or '>20'} | {e['factor']:.0f}× |")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+", type=Path)
    ap.add_argument("--before", action="append", default=[],
                    help="an earlier run with older code, as PATH or PATH=SEED: shown as history, never counted (repeatable)")
    a = ap.parse_args()
    rows = [row(p.resolve()) for p in a.runs]
    k = len(rows)
    go_count = sum(r["go"] for r in rows)
    tasks = list(rows[0]["tasks"])
    lines = ["# Phase 0.2 — habit spike verdict (generated)", "",
             f"Generated by `spike/aggregate.py` from {k} run(s) with the same code: "
             + ", ".join(f"`{r['run'].relative_to(HERE.parent)}` (seed {r['seed']})" for r in rows) + ".", "",
             f"## Verdict: **{'GO' if go_count == k else 'NO-GO'}** — {go_count} of {k} seeds passed all four gates", "",
             "Gates (PLAN 0.2_t): G1 ≥ 60% of steps on habits over the last 5 days · G2 ≥ 95% of the held-out cases a habit "
             "answers are right · G3 tokens per run down ≥ 10× · G4 zero wrong habit answers on planted odd inputs.", "",
             "## Pass rate per gate", "", "| Task | " + " | ".join(GATES) + " |", "|---|" + "---|" * len(GATES)]
    for t in tasks:
        lines.append(f"| {t} | " + " | ".join(f"{sum(r['tasks'][t][g] for r in rows)}/{k}" for g in GATES) + " |")
    lines += ["", "## Every seed", ""] + table(rows)
    if a.before:
        hist = [row(Path(b.split("=")[0]).resolve(), b.split("=")[1] if "=" in b else None) for b in a.before]
        lines += ["", "## History: earlier runs with older code (shown for honesty, never counted)", "",
                  "Each found something the verdict runs then fixed — the friendly fields on the expensive thinking seat, two "
                  "over-strict familiarity rules, and familiarity that only grew on a recompile. The fixes are explained "
                  "in `spike/README.md` and the docstrings of `spike/fingerprint.py` and `spike/run_spike.py`:", ""] + table(hist)
    lines += ["", "**Caveats.** The fixtures are generated and rule-based, so these tasks are compilable by design; real",
              "inboxes are messier and will compile less. The odd inputs were written by the same person who wrote the",
              "checks; the mixed invoice and the fresh seeds are the guard against tuning to them.", ""]
    doc = "\n".join(lines)
    (HERE.parent / "docs" / "spike-go-no-go.md").write_text(doc)
    print(doc)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
