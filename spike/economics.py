#!/usr/bin/env python3
"""What habits cost and save, from a spike run's own ledger (not a gate — the gates are G1-G4).

  break-even   the first day the cumulative tokens WITH habits (every day's calls plus every night's
               teaching, charged the night it happened) drop to or below the cumulative tokens of the
               big brain doing every day alone
  steady state a run's expected cost once learning has settled, from the held-out coverage:
               (1 - coverage) x a big-brain answer + coverage x a fuzzy-field call

  python3 economics.py runs/<stamp>     # prints, and writes ../docs/spike-economics.md
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def econ(run: Path) -> list[dict]:
    res = json.loads((run / "results.json").read_text())
    calls = [json.loads(line) for line in (run / "calls.jsonl").read_text().splitlines()]
    mean = lambda xs: sum(xs) / len(xs) if xs else 0.0  # noqa: E731
    rows = []
    for task, r in res.items():
        big = mean([c["total"] for c in calls if c["purpose"] == f"day:{task}:big"])
        fuzzy = mean([c["total"] for c in calls if c["purpose"] == f"day:{task}:fuzzy"])
        teach_by_day = {n["after_day"]: n["tokens"] for n in r["nights"]}
        with_h = without = 0.0
        breakeven = None
        for d in r["days"]:
            if d.get("skipped"):
                continue
            with_h += d["tokens"] + teach_by_day.get(d["day"], 0)
            without += big
            if breakeven is None and with_h <= without and d["day"] > 3:
                breakeven = d["day"]
        cov = r["metrics"]["heldout_coverage"]
        steady = (1 - cov) * big + cov * fuzzy
        rows.append({"task": task, "big": big, "fuzzy": fuzzy, "teaching": sum(teach_by_day.values()),
                     "with": with_h, "without": without, "breakeven": breakeven, "coverage": cov,
                     "steady": steady, "factor": big / steady if steady else float("inf")})
    return rows


def main(run: Path) -> int:
    rows = econ(run)
    lines = [
        "# Habit spike — economics (generated)", "",
        f"Generated by `spike/economics.py` from `{run.relative_to(HERE.parent)}`. Not a gate; the gates are in "
        "`spike-results.md`.", "",
        "| Task | Big-brain answer | Fuzzy call | Teaching (all nights) | 20 days with habits | 20 days big brain only | Break-even day | Steady state per run | × cheaper |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for x in rows:
        lines.append(
            f"| {x['task']} | {x['big']:,.0f} | {x['fuzzy']:,.0f} | {x['teaching']:,.0f} | {x['with']:,.0f} | {x['without']:,.0f} | "
            f"{x['breakeven'] or 'not within the run'} | {x['steady']:,.0f} ({100 * x['coverage']:.0f}% on habits) | {x['factor']:.1f}× |"
        )
    lines += ["", "Tokens throughout. Steady state uses the held-out coverage measured after day 20.", ""]
    doc = "\n".join(lines)
    print(doc)
    (HERE.parent / "docs" / "spike-economics.md").write_text(doc)
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]).resolve()))
