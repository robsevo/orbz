#!/usr/bin/env python3
"""Generate docs/adoption-ash.md — which Ash Python modules the kit carries (PLAN 0.4).

Read-only against ~/ash. For every module the plan names it records the line count, the test
suites that exist for it (matched by name, then by an actual import or file reference inside the
test so a name collision cannot fake coverage), and any heavy import the slimming must handle.
Nothing in the output is typed by hand; re-run it and diff.

  python3 tools/adoption/ash_map.py            # writes docs/adoption-ash.md
  python3 tools/adoption/ash_map.py --check    # exit 1 if the doc is stale
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

DAEMON = Path.home() / "ash/app/orb/daemon"
OUT = Path(__file__).resolve().parents[2] / "docs/adoption-ash.md"

# The kit's contents, grouped as in PLAN.md "From Ash". Order is presentation order.
GROUPS: dict[str, list[str]] = {
    "voice": ["micaudio", "wake", "stt", "turnend", "speech", "voice", "listen", "sayloop", "voiceturn"],
    "spoken text": ["speakable", "spoken_shape", "spoken_words", "spoken_choice", "lexicon", "phrasing"],
    "learning": ["learning", "learn_gate", "learn_review", "learn_ledger", "voice_distill", "belief_use",
                 "prefs_model", "memindex", "retrieve", "skill_draft", "skill_lifecycle", "skill_usage"],
    "lessons": ["lesson", "lesson_demos", "lessonturn", "teachcanvas", "tutor", "learner_model", "practice_card"],
    "the day": ["day", "dayplan", "day_verbs", "briefs", "proactive", "reminders", "whenparse", "summarize"],
    "safety + honesty": ["oneway", "adapters", "redact", "secretscan", "write_guard", "pagecheck"],
    "chat": ["chatstore"],
}
HEAVY = {"torch", "tflite_runtime", "pyworld", "spacy", "scipy"}
# Desktop couplings the port has to replace (GNOME/X11/PipeWire/EDS).
DESKTOP = re.compile(r"\b(pw-play|paplay|pactl|winplace|deskgeom|gi\.repository|EDS|evolution|xdotool|wmctrl|kgx)\b")


def imports(tree: ast.AST) -> set[str]:
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found |= {a.name.split(".")[0] for a in node.names}
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            found.add(node.module.split(".")[0])
    return found


def tests_for(mod: str, all_tests: list[Path]) -> list[str]:
    """Every suite that really exercises the module: it imports it, or loads it by file name.

    A name match alone is not coverage (test_spoken_sounds.py says nothing about spoken_shape.py),
    and a suite with an unrelated name can be the one that covers a module, so the evidence is the
    import, searched across all suites.
    """
    pat = re.compile(rf"^\s*(import\s+{mod}\b|from\s+{mod}\s+import\b)|\b{mod}\.py\b|['\"]{mod}['\"]", re.M)
    return sorted(t.name for t in all_tests if pat.search(t.read_text(errors="replace")))


def build() -> str:
    if not DAEMON.is_dir():
        raise SystemExit(f"ash_map: CANNOT RUN — {DAEMON} not found")
    all_tests = sorted(DAEMON.glob("test_*.py"))
    lines = [
        "# Ash → Orbs kit: adoption map (generated)",
        "",
        "Generated by `tools/adoption/ash_map.py` from `~/ash/app/orb/daemon` (read-only). Do not edit by",
        "hand; re-run it. **Status** is the checklist: `[ ]` not carried yet, `[x]` carried and its suites",
        "green inside `kit/` (PLAN 0.4_t, 1.3_t).",
        "",
    ]
    total_mods = total_lines = total_tests = 0
    missing = []
    for group, mods in GROUPS.items():
        lines += [f"## {group}", "", "| Module | Lines | Test suites | Heavy imports | Desktop ties | Status |", "|---|---|---|---|---|---|"]
        for mod in mods:
            path = DAEMON / f"{mod}.py"
            if not path.exists():
                missing.append(mod)
                lines.append(f"| `{mod}.py` | — | — | — | — | **missing in Ash** |")
                continue
            src = path.read_text(errors="replace")
            n = src.count("\n")
            heavy = sorted(imports(ast.parse(src)) & HEAVY)
            desk = sorted(set(DESKTOP.findall(src)))
            tests = tests_for(mod, all_tests)
            total_mods += 1
            total_lines += n
            total_tests += len(tests)
            lines.append(
                f"| `{mod}.py` | {n} | {', '.join(f'`{t}`' for t in tests) or '**none**'} | "
                f"{', '.join(heavy) or '—'} | {', '.join(desk) or '—'} | [ ] |"
            )
        lines.append("")
    lines += [
        "## Totals (computed)",
        "",
        f"- modules: {total_mods}" + (f" ({len(missing)} named in the plan but absent: {', '.join(missing)})" if missing else ""),
        f"- lines: {total_lines}",
        f"- test suites matched: {total_tests}",
        "",
        "Heavy imports are what the kit's slimming must remove or make optional (PLAN \"Keeping the kit",
        "slim\"); desktop ties are what the port must replace with cross-platform equivalents.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text() != text
        print("ash_map: STALE — re-run without --check" if stale else "ash_map: up to date")
        return 1 if stale else 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"ash_map: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
